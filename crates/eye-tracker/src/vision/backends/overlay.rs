fn pixel(color: Color) -> image::Rgb<u8> {
    image::Rgb([color.0, color.1, color.2])
}

/// Fill the cells of `text` (each lit glyph dot becomes a `dot`-pixel square, grown by `grow`
/// on every side) with its baseline at `y`.
fn paint_text(image: &mut Frame, text: &str, y: i32, dot: i32, grow: i32, color: Color) {
    let top = y - GLYPH_ROWS as i32 * dot;
    let advance = (GLYPH_COLUMNS as i32 + 1) * dot;
    for (n, ch) in text.chars().enumerate() {
        let glyph = FONT[(ch as usize).clamp(0x20, 0x7E) - 0x20];
        for (col, bits) in glyph.iter().enumerate() {
            for row in 0..GLYPH_ROWS {
                if bits >> row & 1 == 0 {
                    continue;
                }
                let x = 8 + n as i32 * advance + col as i32 * dot - grow;
                let size = (dot + 2 * grow) as u32;
                draw_filled_rect_mut(
                    image,
                    Rect::at(x, top + row as i32 * dot - grow).of_size(size, size),
                    pixel(color),
                );
            }
        }
    }
}

/// Draw a few lines of white text with a dark outline in the top-left corner.
pub fn draw_label(image: &mut Frame, lines: &[String]) {
    let scale = (image.width as f64 / 1000.0).clamp(0.4, 1.2);
    let dot = ((scale * 3.0).round_ties_even() as i32).max(1);
    let mut y = (24.0 * scale) as i32 + 4;
    for text in lines {
        paint_text(image, text, y, dot, 1, (0, 0, 0));
        paint_text(image, text, y, dot, 0, COLOR_TEXT);
        y += (26.0 * scale) as i32 + 4;
    }
}

/// Text lines describing an observation for preview overlays.
pub fn observation_label(obs: &Observation) -> Vec<String> {
    if obs.face_count == 0 {
        return vec!["no face".to_string()];
    }
    let mut lines = Vec::new();
    if let (Some(yaw), Some(pitch)) = (obs.head_yaw, obs.head_pitch) {
        lines.push(format!("yaw {yaw:+.0}  pitch {pitch:+.0}"));
    }
    let mut extras = Vec::new();
    if obs.face_count > 1 {
        extras.push(format!("{} faces", obs.face_count));
    }
    if obs.blink {
        extras.push("eyes closed".to_string());
    }
    if obs.features.is_none() {
        extras.push("unusable".to_string());
    }
    if !extras.is_empty() {
        lines.push(extras.join(", "));
    }
    lines
}

/// Draw a normalised `(x, y, w, h)` box onto `image` in place.
pub fn draw_box(image: &mut Frame, box_: (f64, f64, f64, f64), color: Color, thickness: i32) {
    let (w, h) = (image.width as f64, image.height as f64);
    let (x, y, bw, bh) = box_;
    let x0 = (x * w).round_ties_even() as i32;
    let y0 = (y * h).round_ties_even() as i32;
    let x1 = ((x + bw) * w).round_ties_even() as i32;
    let y1 = ((y + bh) * h).round_ties_even() as i32;
    // The stroke is centred on the outline, like cv2.rectangle.
    for i in 0..thickness.max(1) {
        let grow = i - (thickness.max(1) - 1) / 2;
        let rect = Rect::at(x0 - grow, y0 - grow);
        let (rw, rh) = (x1 - x0 + 2 * grow + 1, y1 - y0 + 2 * grow + 1);
        if rw > 0 && rh > 0 {
            imageproc::drawing::draw_hollow_rect_mut(
                image,
                rect.of_size(rw as u32, rh as u32),
                pixel(color),
            );
        }
    }
}

/// Stroke width that stays visible at any preview resolution.
pub fn line_thickness(image: &Frame) -> i32 {
    ((image.height.max(image.width) as f64 / 640.0).round_ties_even() as i32).max(1)
}
