//! Generate `docs/configuration.md` from the settings metadata in `eye_tracker::config`.
//!
//! ```text
//! cargo xtask gen-config-docs           # rewrite the page
//! cargo xtask gen-config-docs --check   # exit 1 if the page is out of date
//! ```
//!
//! The output does not depend on the platform it is generated on (hotkey defaults
//! are listed for every platform), so CI can check it anywhere.

use std::fs;
use std::path::PathBuf;

use eye_tracker::config::{self, HotkeySettings, PaneSettings, PresenceSettings, SettingRow};
use serde_json::Value;

use crate::repo_root;

fn output() -> PathBuf {
    repo_root().join("docs").join("configuration.md")
}

fn section_title(section: &str) -> String {
    match section {
        "general" => "General",
        "camera" => "Camera",
        "performance" => "Performance",
        "switching" => "Switching",
        "panes" => "Split panes (experimental)",
        "presence" => "Walk-away (presence)",
        "privacy" => "Privacy",
        "hotkeys" => "Hotkeys",
        "learning" => "Learning",
        "updates" => "Updates",
        "ui" => "Interface",
        other => return title_case(other),
    }
    .to_string()
}

/// Python's `str.title()` for the plain ASCII section names.
fn title_case(text: &str) -> String {
    let mut result = String::new();
    let mut start = true;
    for c in text.chars() {
        if c.is_alphabetic() {
            result.extend(if start {
                c.to_uppercase().collect::<Vec<_>>()
            } else {
                c.to_lowercase().collect()
            });
            start = false;
        } else {
            result.push(c);
            start = true;
        }
    }
    result
}

const HEADER: &str = "# Configuration reference

Every option can be changed in **Settings** (tray menu). They are stored in `settings.json`
([where](privacy.md#what-is-stored-and-where); `eye-tracker doctor` prints the exact path, see
[the command line](../README.md#command-line)). Unknown keys are ignored, missing keys use the
defaults below, and out-of-range values are clamped, so a hand-edited file can never stop the app
from starting.

A file that is not valid JSON at all (a missing comma or quote) is renamed to
`settings.json.corrupt`, and **every** setting returns to its default: the hotkeys, the walk-away
action, and also the finished setup assistant, so walking away only shows a notification until you
finish it again. Quit Eye Tracker, fix the file and rename it back to `settings.json`.

Files written by earlier versions are updated when they are loaded. For example, hotkeys that are
still at an earlier version's defaults move to today's defaults once; hotkeys you chose stay.

<!-- Generated by scripts/gen_config_docs.py from eye_tracker.config; do not edit by hand. -->
";

/// The numbers [`section_notes`] quotes from the defaults.
pub struct NoteDefaults {
    pub away_timeout_s: i64,
    pub warning_s: i64,
    /// The default of `hotkeys.toggle_tracking` on this platform.
    pub hotkey_example: String,
    pub after_monitor_switch_ms: i64,
    pub precision: f64,
    pub min_pane_px: i64,
}

impl NoteDefaults {
    pub fn current() -> Self {
        let presence = PresenceSettings::default();
        let panes = PaneSettings::default();
        Self {
            away_timeout_s: presence.away_timeout_s,
            warning_s: presence.warning_s,
            hotkey_example: HotkeySettings::default().toggle_tracking,
            after_monitor_switch_ms: panes.after_monitor_switch_ms,
            precision: panes.precision,
            min_pane_px: panes.min_pane_px,
        }
    }
}

/// A paragraph under a section's heading, for what the rows alone do not say, by section.
///
/// The numbers come from the defaults, so the page cannot contradict them.
pub fn section_notes(defaults: &NoteDefaults) -> Vec<(&'static str, String)> {
    let countdown_starts = defaults.away_timeout_s - defaults.warning_s;
    let pane_example = (defaults.precision * 120.0).max(defaults.min_pane_px as f64);
    vec![
        (
            "panes",
            format!(
                "Off by default. Pane focus follows only on the monitor the cursor is already on, \
                 at the earliest {} ms after a monitor switch, and the \
                 mouse grace of the switching settings applies too. A pane takes part when it is \
                 at least `precision` times the calibration's gaze error and at least \
                 `min_pane_px` wide (panes side by side) or tall (stacked panes): with the defaults \
                 and a gaze error of 120 px that is {pane_example:.0} px. Supported terminals and \
                 the full rules: [split-pane focus](panes.md).",
                defaults.after_monitor_switch_ms
            ),
        ),
        (
            "presence",
            format!(
                "The countdown is part of the away time: with the defaults it appears after \
                 {countdown_starts} s without you, and the action follows at \
                 {} s. Until the setup assistant is finished, `lock`, \
                 `display_off` and `lock_and_display_off` only show a notification. Walk-away \
                 detection needs the camera, so it pauses while tracking is paused, in privacy mode, \
                 during calibration and while another app has the camera.",
                defaults.away_timeout_s
            ),
        ),
        (
            "hotkeys",
            format!(
                "A hotkey is written as modifiers and a key joined by `+`, in any case: `ctrl`, \
                 `alt`, `shift` and `meta` (the Windows key on Windows, Command ⌘ on macOS, Super on \
                 Linux), for example `{}`. An empty value turns that hotkey off. Wayland has \
                 no global hotkeys; see the [platform notes](platform-support.md#wayland).",
                defaults.hotkey_example
            ),
        ),
    ]
}

fn code(value: &str) -> String {
    format!("`{value}`")
}

/// A paragraph wrapped like the hand-written pages (100 columns): `textwrap.fill` without
/// breaking long words or hyphens.
fn wrap(paragraph: &str) -> String {
    const WIDTH: usize = 100;
    let mut lines: Vec<String> = Vec::new();
    let mut length = 0;
    for word in paragraph.split_whitespace() {
        let word_length = word.chars().count();
        match lines.last_mut() {
            Some(line) if length + 1 + word_length <= WIDTH => {
                line.push(' ');
                line.push_str(word);
                length += 1 + word_length;
            }
            _ => {
                lines.push(word.to_string());
                length = word_length;
            }
        }
    }
    lines.join("\n")
}

/// The modifiers of the default hotkeys per platform (`config._HOTKEY_MODIFIERS`).
pub struct HotkeyModifiers {
    pub windows: String,
    pub macos: String,
    pub linux: String,
}

impl HotkeyModifiers {
    pub fn current() -> Self {
        let find = |platform| {
            config::HOTKEY_MODIFIERS
                .iter()
                .find(|(p, _)| *p == platform)
                .map_or(config::HOTKEY_MODIFIERS_OTHER, |(_, m)| m)
                .to_string()
        };
        Self {
            windows: find(config::Platform::Windows),
            macos: find(config::Platform::MacOs),
            linux: config::HOTKEY_MODIFIERS_OTHER.to_string(),
        }
    }
}

/// Python's `str(value)` for the JSON scalar types a setting default can have.
fn plain(value: &Value) -> String {
    match value {
        Value::String(s) => s.clone(),
        other => other.to_string(),
    }
}

fn default_cell(key: &str, value: &Value, modifiers: &HotkeyModifiers) -> String {
    if let (true, Value::String(text)) = (key.starts_with("hotkeys."), value)
        && let Some((_, letter)) = text.rsplit_once('+')
    {
        // The default hotkeys are per platform (config::HOTKEY_MODIFIERS); list
        // each platform only while they differ.
        let platforms = [
            ("Windows", &modifiers.windows),
            ("macOS", &modifiers.macos),
            ("Linux", &modifiers.linux),
        ];
        if platforms.iter().all(|(_, mods)| *mods == platforms[0].1) {
            return code(&format!("{}+{letter}", platforms[0].1));
        }
        return platforms
            .iter()
            .map(|(name, mods)| format!("{} {name}", code(&format!("{mods}+{letter}"))))
            .collect::<Vec<_>>()
            .join("<br>");
    }
    match value {
        Value::Bool(b) => code(if *b { "true" } else { "false" }),
        Value::Array(items) if items.is_empty() => code("[]"),
        Value::Array(items) => code(&items.iter().map(plain).collect::<Vec<_>>().join(", ")),
        other => code(&plain(other)),
    }
}

fn allowed_cell(row: &SettingRow) -> String {
    if !row.choices.is_empty() {
        return row
            .choices
            .iter()
            .map(|c| code(c))
            .collect::<Vec<_>>()
            .join(" · ");
    }
    let (Some(lo), Some(hi)) = (row.lo, row.hi) else {
        return String::new();
    };
    let num = |v: f64| {
        if v.fract() == 0.0 {
            format!("{}", v as i64)
        } else {
            v.to_string()
        }
    };
    format!("{} – {}", num(lo), num(hi))
}

pub fn render_with(
    rows: &[SettingRow],
    notes: &[(&str, String)],
    modifiers: &HotkeyModifiers,
) -> String {
    let mut lines = vec![HEADER.to_string()];
    let mut current = "";
    for row in rows {
        let section = row.key.split('.').next().unwrap_or_default();
        if section != current {
            current = section;
            lines.push(format!("\n## {}\n", section_title(section)));
            if let Some((_, note)) = notes.iter().find(|(name, _)| *name == section) {
                lines.push(format!("{}\n", wrap(note)));
            }
            lines.push("| Key | Default | Allowed | Description |".to_string());
            lines.push("|---|---|---|---|".to_string());
        }
        let doc = row
            .doc
            .split_whitespace()
            .collect::<Vec<_>>()
            .join(" ")
            .replace('|', "\\|");
        lines.push(format!(
            "| {} | {} | {} | {doc} |",
            code(&row.key),
            default_cell(&row.key, &row.default, modifiers),
            allowed_cell(row)
        ));
    }
    lines.join("\n") + "\n"
}

pub fn render() -> String {
    render_with(
        &config::describe_settings(),
        &section_notes(&NoteDefaults::current()),
        &HotkeyModifiers::current(),
    )
}

#[derive(clap::Args, Debug, Clone)]
pub struct Args {
    /// Fail if the page is out of date.
    #[arg(long)]
    pub check: bool,
}

/// Entry point of `cargo xtask gen-config-docs`; returns the exit code.
pub fn main(args: &Args) -> i32 {
    let text = render();
    let output = output();
    if args.check {
        let current = fs::read_to_string(&output).unwrap_or_default();
        if current != text {
            println!("docs/configuration.md is out of date; run cargo xtask gen-config-docs");
            return 1;
        }
        println!("docs/configuration.md is up to date");
        return 0;
    }
    if let Err(e) = fs::write(&output, text) {
        eprintln!("cannot write {}: {e}", output.display());
        return 1;
    }
    println!("wrote docs/configuration.md");
    0
}

